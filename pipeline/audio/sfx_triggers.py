_HOOK_OPENER_KEYWORDS = {"what", "why", "how", "did", "do", "does", "imagine"}


@dataclass(frozen=True)
class WordTiming:
    word: str
    start_frame: int


@dataclass(frozen=True)
class SfxTrigger:
    category: SfxCategory
    word: str
    frame: int
    channel_flavor: str


def _normalize(word: str) -> str:
    return re.sub(r"[^\w$%-]", "", word).lower()


def _channel_flavor(channel: ChannelId) -> str:
    """Per-channel variant selection. NOT bible-sourced -- new design work,
    using channelConfigs.ts's existing `scriptTone` strings as the "genre/
    mood config" the user referred to, since that's the only per-channel
    tone/genre data that already exists in this repo. Simple keyword match
    against the tone description; not a confirmed taxonomy."""
    tones = {
        ChannelId.CH1: "punchy, direct, mind-bending",
        ChannelId.CH2: "analytical, shocking, authoritative",
        ChannelId.CH3: "conspiratorial, terse, urgent",
        ChannelId.CH4: "scientific, vivid, revelatory",
        ChannelId.CH5: "measured, evocative, archival",
        ChannelId.CH6: "awe-inspiring, precise, cosmic",
    }
    tone = tones.get(channel, "")
    if "punchy" in tone or "shocking" in tone or "urgent" in tone:
        return "snappy"
    if "cosmic" in tone or "measured" in tone or "archival" in tone:
        return "deep"
    return "neutral"


def detect_triggers(
    beat: Beat,
    word_timings: list[WordTiming],
    channel: ChannelId,
    *,
    cascade_final_frame: int | None = None,
) -> list[SfxTrigger]:
    """Scans a beat's words for this CHANNEL's trigger keywords (plus the
    universal twist/hook-opener categories).

    For cascade beats, per the user's explicit rule ("SFX hit only on the
    final word/phrase-hold, not every hard-cut word"), this only considers
    the beat's FULL TEXT for a keyword match and -- if found -- fires
    exactly once, at `cascade_final_frame` (the phrase-hold start), never
    per-word. A cascade beat's match always reports CASCADE_PAYOFF
    (highest priority), regardless of which channel keyword matched,
    since the cascade final-word moment IS the big-reveal beat.
    """
    flavor = _channel_flavor(channel)

    if beat.cascade:
        if cascade_final_frame is None:
            raise ValueError("cascade_final_frame is required for cascade beats")
        full_text_words = {_normalize(w) for w in beat.text.split()}
        category = _classify(full_text_words, beat.text, channel)
        if category is None:
            return []
        return [
            SfxTrigger(
                category=SfxCategory.CASCADE_PAYOFF,
                word=beat.text,
                frame=cascade_final_frame,
                channel_flavor=flavor,
            )
        ]

    triggers: list[SfxTrigger] = []
    matched_word_indices: set[int] = set()

    # Multi-word phrase triggers first ("cover-up", "black hole", "lost to
    # history"...) -- these need a sliding window across word_timings,
    # since a single-word scan can never see "lost" + "to" + "history" as
    # one unit. Found this gap while implementing the per-word path below;
    # fixed here rather than left silently broken for non-cascade beats.
    for category, phrases in _PHRASE_TRIGGERS.get(channel, {}).items():
        for phrase in phrases:
            phrase_words = phrase.split()
            n = len(phrase_words)
            for i in range(len(word_timings) - n + 1):
                window = [_normalize(word_timings[i + j].word) for j in range(n)]
                if window == phrase_words:
                    triggers.append(
                        SfxTrigger(category=category, word=phrase, frame=word_timings[i].start_frame, channel_flavor=flavor)
                    )
                    matched_word_indices.update(range(i, i + n))

    for idx, wt in enumerate(word_timings):
        if idx in matched_word_indices:
            continue  # already covered by a phrase match above
        norm = _normalize(wt.word)
        category = _classify({norm}, wt.word, channel)
        if category is not None:
            triggers.append(SfxTrigger(category=category, word=wt.word, frame=wt.start_frame, channel_flavor=flavor))
    return triggers


def _classify(normalized_words: set[str], raw_text: str, channel: ChannelId) -> SfxCategory | None:
    raw_lower = raw_text.lower()

    channel_cats = _CHANNEL_KEYWORDS.get(channel, {})
    # Tier 1 then tier 2, in priority order, checking this channel's own categories only.
    for category, keywords in sorted(channel_cats.items(), key=lambda kv: kv[0]):
        if "$" in raw_text and "$" in keywords:
            return category
        if normalized_words & keywords:
            return category

    for category, phrases in _PHRASE_TRIGGERS.get(channel, {}).items():
        if any(p in raw_lower for p in phrases):
            return category

    if channel == ChannelId.CH5:
        for w in normalized_words:
            if _YEAR_RE.match(w):
                return SfxCategory.DATE_EVENT

    if normalized_words & _TWIST_KEYWORDS:
        return SfxCategory.TWIST
    if normalized_words & _HOOK_OPENER_KEYWORDS:
        return SfxCategory.HOOK_OPENER
    return None


def resolve_conflicts(triggers: list[SfxTrigger], fps: int, min_gap_ms: int = MIN_GAP_MS) -> list[SfxTrigger]:
    """Enforces the minimum gap between cues; when two triggers land within
    the gap, keeps only the higher-priority one (lower SfxCategory value)."""
    min_gap_frames = round(min_gap_ms / 1000 * fps)
    ordered = sorted(triggers, key=lambda t: t.frame)

    kept: list[SfxTrigger] = []
    for trigger in ordered:
        conflict_idx = None
        for i, existing in enumerate(kept):
            if abs(trigger.frame - existing.frame) < min_gap_frames:
                conflict_idx = i
                break
        if conflict_idx is None:
            kept.append(trigger)
            continue
        if trigger.category < kept[conflict_idx].category:  # lower value = higher priority
            kept[conflict_idx] = trigger
    return sorted(kept, key=lambda t: t.frame)


# --- Placeholder tones -- NOT real SFX, see module docstring ---
#
# Three generator "shapes" so categories are audibly distinguishable, not
# just different pitches of the same beep:
#   "tone"  -- a sine at a fixed frequency (original approach)
#   "sweep" -- aevalsrc chirp, frequency rises or falls linearly over the
#              cue's duration (genuine riser/reverse-riser, not simulated)
#   "burst" -- bandpassed white noise (anoisesrc + bandpass), for
#              paper/static/rumble-ish textures ffmpeg can produce without
#              a real sampled asset

@dataclass(frozen=True)
class _ToneSpec:
    shape: str  # "tone" | "sweep" | "burst"
    freq_low: float
    freq_high: float | None = None  # for "sweep": start freq; freq_low is end freq if descending
    duration_s: float = 0.25
    bandpass_width: float | None = None  # for "burst"


_TONE_SPECS: dict[SfxCategory, _ToneSpec] = {
    SfxCategory.CASCADE_PAYOFF: _ToneSpec("sweep", freq_low=400, freq_high=1200, duration_s=0.4),  # genuine rising riser
    SfxCategory.MONEY: _ToneSpec("tone", freq_low=1200, duration_s=0.25),  # unchanged from prior pass
    SfxCategory.PSYCHOLOGY_TERM: _ToneSpec("tone", freq_low=500, duration_s=0.35),  # soft, lower, longer fade = "soft pulse"
    SfxCategory.STUDY_STAT: _ToneSpec("tone", freq_low=1600, duration_s=0.12),  # quick high chime, distinct from psych pulse
    SfxCategory.CLASSIFIED: _ToneSpec("burst", freq_low=300, bandpass_width=200, duration_s=0.2),  # paper-rustle-ish + low thud character via bandpass center
    SfxCategory.COVERUP: _ToneSpec("tone", freq_low=100, duration_s=0.4),  # low, slow, moody
    SfxCategory.NEURO_TERM: _ToneSpec("tone", freq_low=900, duration_s=0.1),  # sharp/fast high blip -- distinct from CH1's soft low pulse
    SfxCategory.MEMORY: _ToneSpec("sweep", freq_low=900, freq_high=300, duration_s=0.3),  # falling = "reverse riser"/glitch
    SfxCategory.DATE_EVENT: _ToneSpec("burst", freq_low=800, bandpass_width=400, duration_s=0.15),  # mechanical click-ish (film-reel/page-turn), different band than CH3's rustle
    SfxCategory.LOST_TO_HISTORY: _ToneSpec("tone", freq_low=220, duration_s=0.6),  # long slow swell
    SfxCategory.SCALE_DISTANCE: _ToneSpec("burst", freq_low=70, bandpass_width=60, duration_s=0.5),  # deep rumble
    SfxCategory.DISCOVERY: _ToneSpec("burst", freq_low=2500, bandpass_width=1500, duration_s=0.15),  # radio-static-ish blip, high band
    SfxCategory.TWIST: _ToneSpec("tone", freq_low=220, duration_s=0.25),
    SfxCategory.HOOK_OPENER: _ToneSpec("tone", freq_low=1800, duration_s=0.25),
}


def generate_placeholder_tone(category: SfxCategory, out_path: Path) -> None:
    """Synthesizes a labeled placeholder cue -- NOT a real SFX asset. See
    module docstring for why, and for what's NOT_SOURCED about
    normalization."""
    spec = _TONE_SPECS[category]
    out_path.parent.mkdir(parents=True, exist_ok=True)
    fade_d = spec.duration_s * 0.6

    if spec.shape == "tone":
        filter_complex = f"sine=frequency={spec.freq_low}:duration={spec.duration_s}"
        af = f"afade=t=out:st=0:d={fade_d}"
        cmd = [ffmpeg_path(), "-y", "-f", "lavfi", "-i", filter_complex, "-af", af, str(out_path)]
    elif spec.shape == "sweep":
        # Genuine linear frequency sweep via aevalsrc, not a fixed tone.
        f0, f1 = spec.freq_low, spec.freq_high
        expr = f"sin(2*PI*t*({f0}+({f1}-{f0})*t/{spec.duration_s})/2)"
        cmd = [
            ffmpeg_path(), "-y", "-f", "lavfi",
            "-i", f"aevalsrc={expr}:d={spec.duration_s}",
            "-af", f"afade=t=out:st=0:d={fade_d}",
            str(out_path),
        ]
    elif spec.shape == "burst":
        center = spec.freq_low
        width = spec.bandpass_width or center
        cmd = [
            ffmpeg_path(), "-y", "-f", "lavfi",
            "-i", f"anoisesrc=color=white:duration={spec.duration_s}",
            "-af", f"bandpass=f={center}:width_type=h:w={width},afade=t=out:st=0:d={fade_d}",
            str(out_path),
        ]
    else:
        raise ValueError(f"unknown tone shape {spec.shape!r}")

    result = subprocess.run(cmd, capture_output=True, text=True)
    if result.returncode != 0:
        raise RuntimeError(f"ffmpeg placeholder cue generation failed ({category.name}):\n{result.stderr}")
