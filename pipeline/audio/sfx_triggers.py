MIN_GAP_MS = 175  # midpoint of the user's specified 150-200ms range; not
# independently sourced from a bible or repo -- the user asked for
# "minimum 150-200ms," not one exact number, so this is a documented choice
# within that range, not outside it.


class SfxCategory(IntEnum):
    """Priority tiers -- lower value = higher priority, per the user's
    original rule ("money/number > generic"), generalized to 6 channels:
    cascade payoff > this channel's primary topic category > this
    channel's secondary topic category > twist > hook-opener. Cross-
    channel comparisons never actually happen (detect_triggers is always
    scoped to one channel), so channel-specific categories only need to be
    correctly ordered relative to each OTHER category that same channel
    can produce, not globally unique."""

    CASCADE_PAYOFF = 0  # universal -- cascade-beat final-word/phrase-hold hit

    # Tier 1: each channel's primary topic category
    MONEY = 10  # CH2
    PSYCHOLOGY_TERM = 11  # CH1
    CLASSIFIED = 12  # CH3
    NEURO_TERM = 13  # CH4
    DATE_EVENT = 14  # CH5
    SCALE_DISTANCE = 15  # CH6

    # Tier 2: each channel's secondary topic category
    STUDY_STAT = 20  # CH1
    COVERUP = 21  # CH3
    MEMORY = 22  # CH4
    LOST_TO_HISTORY = 23  # CH5
    DISCOVERY = 24  # CH6

    # Universal, lowest priority
    TWIST = 30
    HOOK_OPENER = 40


